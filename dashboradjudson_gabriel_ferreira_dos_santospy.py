"""12. Função calcular_nota_final_e_situacao"""

def calcular_nota_final_e_situacao(df):
    """
    Calcula a nota final e define a situação do aluno.

    Regra usada:
    nota_final = prova_1 + atividade_1 + prova_2 + atividade_2

    Se nota_final for maior ou igual a 70, o aluno está aprovado.
    Caso contrário, está reprovado.
    """

    df["nota_final"] = (
        df["prova_1"] +
        df["atividade_1"] +
        df["prova_2"] +
        df["atividade_2"]
    )

    df["situacao"] = df["nota_final"].apply(
        lambda nota: "Aprovado" if nota >= 70 else "Reprovado"
    )

    return df

