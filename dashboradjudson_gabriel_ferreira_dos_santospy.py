def converter_notas_para_numero(df):
    """
    Converte as colunas de notas para valores numéricos.

    Caso algum valor esteja com vírgula decimal, como "8,5",
    a função troca a vírgula por ponto antes da conversão.
    """

    colunas_notas = ["atividade_1", "prova_1", "atividade_2", "prova_2"]

    for coluna in colunas_notas:
        df[coluna] = pd.to_numeric(df[coluna], errors="coerce")

    return df

